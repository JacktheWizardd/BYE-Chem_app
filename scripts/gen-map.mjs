// Turns docs/chapter-map.md (the one hand-edited source) into src/content/map.generated.ts.
//   node scripts/gen-map.mjs          write the file
//   node scripts/gen-map.mjs --check  fail if the file is out of date (used by `npm run check`)
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = path.join(root, 'docs/chapter-map.md');
const out = path.join(root, 'src/content/map.generated.ts');
const md = readFileSync(src, 'utf8');

const LEVELS = ['Intro', '1A', '1B', 'AP'];
const cells = (line) => line.split('|').slice(1, -1).map((c) => c.trim());
const refs = (s) => (s.match(/\d+\.\d+/g) ?? []);

const chapters = md.split(/^## Chapter /m).slice(1).map((block) => {
  const lines = block.split('\n');
  const [num, title] = lines[0].split(' · ');
  const meta = lines[1];
  const question = meta.match(/^\*(.+?)\*/)[1];
  const parts = meta.split(' · ').map((p) => p.trim());
  const tro = (parts.find((p) => p.startsWith('Tro')) ?? '').replace(/^Tro /, '');
  const links = parts.filter((p) => /^(Lab|Tools|Viewer):/.test(p));
  const sections = lines
    .filter((l) => /^\| \d+\.\d+ \|/.test(l))
    .map((l) => {
      const [id, stitle, q, troRefs, levelCell, needs] = cells(l);
      const words = levelCell.split(/\s+/);
      const levels = LEVELS.filter((k) => words.includes(k));
      const apUnit = words.find((w) => /^U\d$/.test(w));
      return { id, title: stitle, question: q, tro: troRefs === 'App. I' ? ['App. I'] : refs(troRefs), levels, ...(apUnit ? { apUnit } : {}), needs: refs(needs) };
    });
  const levels = LEVELS.filter((k) => sections.some((s) => s.levels.includes(k)));
  return { num: Number(num), title: title.trim(), question, tro, levels, links, sections };
});

const classOrder = md
  .split(/^## Class order/m)[1]
  .split('\n')
  .filter((l) => /^\| [\d,\s.–]+ \|/.test(l))
  .map((l) => { const [tro, ours] = cells(l); return { tro, ours }; });

const body = `// GENERATED by scripts/gen-map.mjs from docs/chapter-map.md. Do not edit by hand; edit the map and run \`npm run gen:map\`.
import type { MapChapter } from './types';

export const CHAPTER_MAP: MapChapter[] = ${JSON.stringify(chapters, null, 2)};

export const CLASS_ORDER: { tro: string; ours: string }[] = ${JSON.stringify(classOrder, null, 2)};
`;

if (process.argv.includes('--check')) {
  if (!existsSync(out) || readFileSync(out, 'utf8') !== body) {
    console.error('src/content/map.generated.ts is out of date. Run `npm run gen:map`.');
    process.exit(1);
  }
  console.log(`map up to date: ${chapters.length} chapters, ${chapters.reduce((n, c) => n + c.sections.length, 0)} sections`);
} else {
  writeFileSync(out, body);
  console.log(`wrote ${path.relative(root, out)}: ${chapters.length} chapters, ${chapters.reduce((n, c) => n + c.sections.length, 0)} sections`);
}
